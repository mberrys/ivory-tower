// @ts-check
'use strict';

/**
 * IV-19: deterministically renders configs/ivory-third-party-inventory.json
 * into THIRD-PARTY-NOTICES-ivory-tower.md. Ivory Tower's own dependency
 * notices are kept separate from NOTICE.md, which upstream Theia's
 * dash-licenses gate (license-check.yml) generates and owns.
 * Run via: npm run notices:generate:ivory-tower
 * Checked (without writing) via: npm run notices:check:ivory-tower
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'THIRD-PARTY-NOTICES-ivory-tower.md');

export function renderNotices() {
    const inventory = JSON.parse(fs.readFileSync(path.join(root, 'configs', 'ivory-third-party-inventory.json'), 'utf8'));
    const policy = JSON.parse(fs.readFileSync(path.join(root, 'configs', 'ivory-dependency-policy.json'), 'utf8'));
    const entries = [...inventory.entries].sort((left, right) => left.name.localeCompare(right.name));

    const lines = [];
    lines.push('# Ivory Tower third-party notices');
    lines.push('');
    lines.push('Generated from `configs/ivory-third-party-inventory.json` by `scripts/generate-ivory-notices.mjs` (IV-19).');
    lines.push('Do not hand-edit; edit the inventory JSON and regenerate with `npm run notices:generate:ivory-tower`.');
    lines.push('');
    lines.push(
        'This covers dependencies and technologies owned by Ivory Tower packages. Upstream Theia\'s own ' +
            'third-party notices are tracked separately in [`NOTICE.md`](./NOTICE.md), generated by the ' +
            'upstream `license:check` (dash-licenses) gate.',
    );
    lines.push('');
    lines.push('## Entries');
    lines.push('');
    for (const entry of entries) {
        lines.push(`### ${entry.name}`);
        lines.push('');
        lines.push(`* Kind: ${entry.kind}`);
        lines.push(`* Status: ${entry.status}`);
        lines.push(`* Used by: ${entry.usedBy.join(', ')}`);
        lines.push(`* License: ${entry.license}`);
        lines.push(`* Purpose: ${entry.purpose}`);
        lines.push(`* Owner: ${entry.owner}`);
        lines.push(`* Version policy: ${entry.versionPolicy}`);
        lines.push(`* Replacement path: ${entry.replacementPath}`);
        lines.push(`* Network-capable: ${entry.networkCapable}`);
        lines.push(`* Native/runtime requirement: ${entry.nativeOrRuntimeRequirement}`);
        lines.push(`* Source content crosses this boundary: ${entry.sourceContentCrossesBoundary}`);
        if (entry.notes) {
            lines.push(`* Notes: ${entry.notes}`);
        }
        lines.push('');
    }

    lines.push('## Recorded advisory exceptions');
    lines.push('');
    if (policy.advisoryExceptions.length === 0) {
        lines.push('None recorded.');
    } else {
        for (const exception of policy.advisoryExceptions) {
            lines.push(`* ${exception.package} — ${exception.advisory}: ${exception.reason} (owner: ${exception.owner}, expires: ${exception.expires})`);
        }
    }
    lines.push('');

    return `${lines.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    fs.writeFileSync(outputPath, renderNotices());
    console.log(`Wrote ${path.relative(root, outputPath)}.`);
}
